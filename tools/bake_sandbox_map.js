/* Bake the whole Lost Temple map into a PNG data URI for the console's sandbox, painted the way the
   old console paints its map: one pixel per 32-unit cell; plus building footprints and the mines.
   node tools/bake_sandbox_map.js > web/data/sandbox-map.js   (generated: do not edit) */
const path = require('path'), zlib = require('zlib');
const web = path.join(__dirname, '..', 'web');
global.window = global;
require(path.join(web, 'data/lost-temple.js'));
const Sim = require(path.join(web, 'sim.js'));
const D = window.LT_DATA, W = new Sim.World(D);
const TILE = {Ldrt: [86, 72, 50], Ldro: [76, 64, 46], Ldrg: [74, 86, 50], Ysqd: [98, 94, 82], Yrtl: [88, 84, 74], Lgrs: [58, 84, 44], Yhdg: [52, 70, 40]};
// the whole map
const X0 = W.ox, X1 = W.ox + W.W * 32, Y0 = W.oy, Y1 = W.oy + W.H * 32;
const gx0 = Math.floor((X0 - W.ox) / 32), gx1 = Math.ceil((X1 - W.ox) / 32), gy0 = Math.floor((Y0 - W.oy) / 32), gy1 = Math.ceil((Y1 - W.oy) / 32);
const w = gx1 - gx0, h = gy1 - gy0;
const T = D.terrain, raw = Buffer.from(T.data, 'base64'), tiles = T.tiles.map(n => TILE[n] || [70, 70, 60]);
const px = Buffer.alloc(w * h * 3);
const tree = new Uint8Array(W.W * W.H);
W.trees.forEach(t => t.walk.forEach(i => { tree[i] = 1 + (t.id % 3); }));
for (let gy = gy0; gy < gy1; gy++) for (let gx = gx0; gx < gx1; gx++) {
  const i = gy * W.W + gx;
  let c;
  if (gx < 0 || gy < 0 || gx >= W.W || gy >= W.H) c = [12, 16, 14];
  else if (tree[i]) c = (gx + gy + tree[i]) % 3 ? [16 + (tree[i] * 13) % 10, 40 + (tree[i] * 7) % 12, 18] : [28, 58, 26];
  else {
    const tx = Math.min(T.w - 1, Math.round((gx * 32 + 16) / 128)), ty = Math.min(T.h - 1, Math.round((gy * 32 + 16) / 128));
    const v = raw[ty * T.w + tx], b = tiles[v & 15], cliff = v >> 4, n = ((gx * 7349 + gy * 1931) % 9) - 4, k = W.sBlock[i] ? 0.42 : cliff ? 0.8 : 1;
    c = [Math.max(0, b[0] * k + n) | 0, Math.max(0, b[1] * k + n) | 0, Math.max(0, b[2] * k + n) | 0];
  }
  const o = ((gy1 - 1 - gy) * w + (gx - gx0)) * 3; px[o] = c[0]; px[o + 1] = c[1]; px[o + 2] = c[2];
}
// PNG
const crcT = new Int32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c; });
const crc = b => { let c = -1; for (const x of b) c = crcT[(c ^ x) & 255] ^ (c >>> 8); return (c ^ -1) >>> 0; };
const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([len, td, c]); };
const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 2;
const rows = Buffer.alloc((w * 3 + 1) * h); for (let y = 0; y < h; y++) px.copy(rows, y * (w * 3 + 1) + 1, y * w * 3, (y + 1) * w * 3);
const png = Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(rows, {level: 9})), chunk('IEND', Buffer.alloc(0))]);
// buildings' footprints (solid part) for drawing: by type
const body = {};
for (const t of ['htow', 'hkee', 'halt', 'hbar', 'hhou', 'hlum', 'hwtw', 'hatw', 'hvlt', 'hars', 'hbla']) {
  const tex = W.buildingTex(t); if (!tex) continue; const r = W.bodyRect(0, 0, tex), f = W.rectOf(0, 0, tex); body[t] = {body: r, foot: f};
}
const mines = W.mines.filter(m => m.x > X0 && m.x < X1 && m.y > Y0 && m.y < Y1).map(m => ({x: m.x, y: m.y, body: W.bodyRect(m.x, m.y, m.tex)}));
process.stdout.write('/* Generated by tools/bake_sandbox_map.js. Do not edit. */\nwindow.MAPDATA=' + JSON.stringify({png: 'data:image/png;base64,' + png.toString('base64'), x0: gx0 * 32 + W.ox, y0: gy0 * 32 + W.oy, x1: gx1 * 32 + W.ox, y1: gy1 * 32 + W.oy, w, h, body, mines}) + ';\n');
